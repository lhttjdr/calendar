def day_rows(t):
    fname, title, juan, men, ce, pages, months, notes, checks, tail = t
    rows = []
    for m, s in enumerate(months, start=1):
        if s is None:
            rows.append([title, juan, men, ce, pages[m - 1], m, "", "", "", "", checks.get(m, "未录")])
            continue
        main, _, wai = s.partition("|")
        for kind, part in (("正", main), ("外", wai)):
            for g in GZ.findall(part):
                rows.append([title, juan, men, ce, pages[m - 1], m, g, kind, notes.get(m, ""), s.replace("|", "　外"), checks.get(m, "")])
    rows.append([title, juan, men, ce, pages[-1], 0, "", "", tail, "", ""])
    return rows


