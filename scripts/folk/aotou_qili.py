def show_spec(spec):
    """值说明 → 文档显示用。"""
    if spec.startswith("季:"):
        return " ".join(spec[2:].split("|"))
    if spec.startswith("月:"):
        return "｜".join(spec[2:].split("|"))
    return spec


def cmp(a, b):
    same = len(a & b)
    return same, len(a - b), len(b - a)


def summarize(s):
    """720 日集合 → 每月值的简写（同支者写支，同干者写干，否则列干支）。"""
    out = []
    for m in range(1, 13):
        ks = sorted(k for mm, k in s if mm == m)
        zs = {GZ60[k][1] for k in ks}
        gs = {GZ60[k][0] for k in ks}
        if not ks:
            out.append("-")
        elif all(sum(1 for k in ks if GZ60[k][1] == z) == 5 for z in zs):
            out.append("".join(z for z in ZHI if z in zs))
        elif all(sum(1 for k in ks if GZ60[k][0] == g) == 6 for g in gs):
            out.append("".join(g for g in GAN if g in gs))
        else:
            out.append("".join(GZ60[k] for k in ks))
    if all(len(x) == 1 for x in out):
        return "".join(out)
    return "｜".join(out)


