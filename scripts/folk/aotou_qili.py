def items_of(s):
    """一串 → 值列表：先按干支两字切，否则逐字。"""
    g = GZRE.findall(s)
    if g and "".join(g) == s:
        return g
    return list(s)


def months_of(spec):
    """值说明 → 12 个月的值列表（每月一列表）。"""
    if spec.startswith("季:"):
        out = [None] * 12
        for part in spec[2:].split("|"):
            for m in SEASON[part[0]]:
                out[m - 1] = items_of(part[1:])
        return out
    if spec.startswith("月:"):
        ms = spec[2:].split("|")
        assert len(ms) == 12, spec
        return [[x for x in m.split("+") if x] for m in ms]
    v = items_of(spec)
    assert len(v) == 12, (spec, len(v))
    return [[x] for x in v]


def day_set(months):
    """12 个月的值列表 → {(月, 干支序)}。单字为干者比日干、为支者比日支，两字比干支。"""
    s = set()
    for m, vals in enumerate(months, 1):
        for v in vals or []:
            for k in range(60):
                g = GZ60[k]
                if (len(v) == 2 and g == v) or (v in GAN and g[0] == v) or (v in ZHI and g[1] == v):
                    s.add((m, k))
    return s


def list_set(s):
    """不分月之干支串 → 720 日中逢之者。"""
    g = set(GZRE.findall(s))
    return {(m, k) for m in range(1, 13) for k in range(60) if GZ60[k] in g}


