def walk(start, seq, forward=True):
    """正月起 start，在 seq（四孟/四仲/四季/六阳/六阴/十二辰）中顺或逆行，得十二个月的值"""
    i = seq.index(start)
    step = 1 if forward else -1
    return [seq[(i + step * k) % len(seq)] for k in range(12)]


def season(spring, summer, autumn, winter):
    """春夏秋冬各三个月"""
    out = []
    for v in (spring, summer, autumn, winter):
        out += [v] * 3
    return out


def months(s):
    """「丙甲壬庚」按正五九、二六十……循环，或十二个以空格分隔的值"""
    parts = s.split()
    if len(parts) == 12:
        return parts
    if len(s) == 4 and " " not in s:
        return [s[k % 4] for k in range(12)]
    raise ValueError(s)


ROWS = []


def add(name, good, kind, vals, src):
    assert len(vals) == 12, name
    ROWS.append((name, "吉" if good else "凶", kind, "|".join(vals), src))


