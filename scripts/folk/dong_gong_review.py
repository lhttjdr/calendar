# ---------- 施校 ----------
GAN = "甲乙丙丁戊己庚辛壬癸"
ORDER = ["諸事", "起造", "修造", "動土", "豎造", "作灶", "安門", "作倉庫", "作欄", "婚姻", "納采", "會親", "入宅", "移居",
         "開張", "出行", "上官", "見貴", "上學", "安葬", "破土", "生基", "還愿"]

ents, rows = tables.build()
ent_key = {(int(e["月"]), e["建除"]): e for e in ents}


def mk(m, gz, jc, ev, v, g, basis, cond, note):
    return {"月": str(m), "干支": gz, "建除": jc, "事": ev, "宜忌": v, "等第": g, "泛言": "是" if ev == "諸事" else "",
            "依据": basis, "条件": cond, "校": note}


def addnote(r, n):
    if n:
        r["校"] = (r["校"] + "；" if r["校"] else "") + n


enotes = {}
for (m, jc), ops in F.items():
    zhi = ent_key[(m, jc)]["日支"]
    for op in ops:
        kind = op[0]
        if kind == "entry":
            enotes.setdefault((m, jc), []).append(op[1])
            continue
        gzs = [g + zhi for g in op[1]]
        for g in gzs:
            assert (GAN.index(g[0]) - "子丑寅卯辰巳午未申酉戌亥".index(zhi)) % 2 == 0, (m, jc, g)
        if kind in ("set", "add"):
            _, _, new, note = op
            if kind == "set":
                rows = [r for r in rows if not (int(r["月"]) == m and r["干支"] in gzs)]
            for gz in gzs:
                for evs, v, g, basis, cond in new:
                    for ev in evs.split():
                        assert ev in ORDER, ev
                        # 同日同事同条件后出者覆盖
                        rows = [r for r in rows if not (int(r["月"]) == m and r["干支"] == gz and r["事"] == ev and r["条件"] == cond)]
                        rows.append(mk(m, gz, jc, ev, v, g, basis, cond, note))
        else:
            evs = op[2].split() if op[2] else None
            hit = [r for r in rows if int(r["月"]) == m and r["干支"] in gzs and (evs is None or r["事"] in evs)]
            assert hit or kind == "del", (m, jc, op)
            if kind == "del":
                rows = [r for r in rows if r not in hit]
                if op[3]:
                    enotes.setdefault((m, jc), []).append(f"{'、'.join(gzs)}：{op[3]}")
            elif kind == "grade":
                for r in hit:
                    r["等第"] = op[3]
                    addnote(r, op[4])
            elif kind == "cond":
                for r in hit:
                    r["条件"] = op[3]
                    addnote(r, op[4])
            elif kind == "note":
                for r in hit:
                    addnote(r, op[3])

