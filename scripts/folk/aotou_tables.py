def jiaqu_rows():
    rows = []
    for page, title, months, tail, notes in (QIUHUN, XIADING):
        for m, s in enumerate(months, start=1):
            main, _, wai = s.partition("|")
            for kind, part in (("正", main), ("外", wai)):
                for g in gzs(part):
                    rows.append([title, "卷三", "婚姻", 4, page, m, g, kind, "", s.replace("|", "　外"), notes.get(m, "")])
        rows.append([title, "卷三", "婚姻", 4, page, 0, "", "", tail, "", ""])
    for page, title, months, tail, notes in (JIAQU, BEIJI):
        for m, groups in enumerate(months, start=1):
            if groups is None:
                rows.append([title, "卷三", "婚姻", 4, page, m, "", "", "", "", notes.get(m, "未录")])
                continue
            text = "".join(a + b for a, b in groups)
            pg = page + (1 if (title == "逐月嫁娶吉日" and m >= 7) or (title == "逐月嫁娶結婚吉日備急用" and m == 12) else 0)
            for days, note in groups:
                for g in gzs(days):
                    rows.append([title, "卷三", "婚姻", 4, pg, m, g, "正", note, text, notes.get(m, "")])
        rows.append([title, "卷三", "婚姻", 4, page, 0, "", "", tail, "", ""])
    return rows


def write_jiaqu(path):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["表", "卷", "门", "册", "页", "月", "干支", "等", "注", "原文", "校"])
        w.writerows(jiaqu_rows())


