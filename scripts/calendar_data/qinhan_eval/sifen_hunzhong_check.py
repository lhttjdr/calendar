"""后汉四分历二十四气昏中星表（《后汉书·律历志下》，点校本第十一册页 3077—3079）与实际天象几何比较：检验「由昏中星反推日躔」能否
造成汉代日食宿度的系统偏差。

表中「昏中星去日」= 昏中星 − 日所在（汉代赤道宿度，周天 365¼，日所在之分以 32 为分母）。实际值 = 日入时角（洛阳北纬 34.7°，
太阳上缘、折射 34′）+ 昏刻 2.5 刻（36 分钟恒星时），按周天 365¼ 换为古度。两者之差就是用此表由实测昏中星推日躔时的系统偏差
（正为推得日躔偏西）。另算《汉书·天文志》太初时期二分二至昏中星（冬至奎八、春分柳一、夏至氐十三、秋分牵牛三度七分），日躔按三统历。

判读：谷雨「張十七」、立夏「翼十七大」，扫描中「十」与「七」上下连写。
输出 data/phenomena/checks/sifen_hunzhong.csv。用法（仓库根）：python3 scripts/calendar_data/qinhan_eval/sifen_hunzhong_check.py
"""
import csv
import math
from pathlib import Path
W=dict(zip("角亢氐房心尾箕斗牛女虚危室壁奎娄胃昴毕觜参井鬼柳星张翼轸",[12,9,15,5,5,18,11,26.25,8,12,10,17,16,9,16,12,14,11,16,2,9,33,4,15,7,18,18,17]))
ORD="角亢氐房心尾箕斗牛女虚危室壁奎娄胃昴毕觜参井鬼柳星张翼轸"
def pos(l,d):
    x=0
    for c in ORD:
        if c==l: return x+d
        x+=W[c]
FR={'':0,'少':.25,'半':.5,'大':.75,'太':.75}
def q(s):  # 「奎六弱」「婁六半强」
    l=s[0]; r=s[1:]; adj=0
    if r.endswith('强'): adj=1/12; r=r[:-1]
    if r.endswith('弱'): adj=-1/12; r=r[:-1]
    f=0
    if r and r[-1] in '少半大': f=FR[r[-1]]; r=r[:-1]
    D="〇一二三四五六七八九"; v=cur=0
    for c in r:
        if c=='十': v+=(cur or 1)*10; cur=0
        else: cur=D.index(c)
    return pos(l, v+cur+f+adj)
# 四分历二十四气（《后汉书·律历志下》，点校本页 3077—3079）：(气, 日所在宿, 度, 分/32, 昏中星, 旦中星)
T=[('冬至','斗',21,8,'奎六弱','亢二少强'),('小寒','女',2,7,'娄六半强','氐七少弱'),('大寒','虚',5,14,'胃十一半强','心半'),
('立春','危',10,21,'毕五少弱','尾七半弱'),('雨水','室',8,28,'参六半弱','箕大弱'),('惊蛰','壁',8,3,'井十七少弱','斗少'),
('春分','奎',14,10,'鬼四','斗十一弱'),('清明','胃',1,17,'星四大','斗二十一半'),('谷雨','昴',2,24,'张十七','牛六半'),
('立夏','毕',6,31,'翼十七大','女十少'),('小满','参',4,6,'角大弱','危大弱'),('芒种','井',10,13,'亢五大','危十四强'),
('夏至','井',25,20,'氐十二少弱','室十二少弱'),('小暑','柳',3,27,'尾一大强','奎二大强'),('大暑','星',4,2,'尾十五半弱','娄三大'),
('立秋','张',12,9,'箕九大强','胃九大弱'),('处暑','翼',9,16,'斗十少','毕三大'),('白露','轸',6,23,'斗二十一强','参五半弱'),
('秋分','角',4,30,'牛五少','井十六少强'),('寒露','亢',8,1,'女七大','鬼三少强'),('霜降','氐',14,12,'虚六大','星三大强'),
('立冬','尾',4,19,'危八强','张十五大强'),('小雪','箕',1,26,'室三半强','翼十五大强'),('大雪','斗',6,1,'壁半强','轸十五弱')]
Z=365.25; phi=math.radians(34.7); eps=math.radians(23.68)
rows=[]
for i,(n,l,d,f,h,dn) in enumerate(T):
    sun=pos(l,d+f/32); D=(q(h)-sun)%Z
    lam=math.radians(270+i*360/24)
    dec=math.asin(math.sin(eps)*math.sin(lam))
    H0=math.degrees(math.acos(-math.tan(phi)*math.tan(dec)-0.0145/ (math.cos(phi)*math.cos(dec))))
    act=(H0+2.5*14.4/60*15.041)*Z/360
    rows.append(["四分历", n, h, f"{D:.2f}", f"{act:.2f}", f"{D-act:+.2f}"])
# 太初（《汉书·天文志》）：冬至昏奎八中、夏至氐十三、春分柳一、秋分牵牛三度七分；日躔按三统历：冬至牛初、春分娄四、夏至井三十一、秋分角十
for n,sun,h,i in (('冬至',pos('牛',0),pos('奎',8),0),('春分',pos('娄',4),pos('柳',1),6),('夏至',pos('井',31),pos('氐',13),12),('秋分',pos('角',10),pos('牛',3+7/32),18)):
    D=(h-sun)%Z; lam=math.radians(270+i*15); dec=math.asin(math.sin(eps)*math.sin(lam))
    H0=math.degrees(math.acos(-math.tan(phi)*math.tan(dec)-0.0145/(math.cos(phi)*math.cos(dec))))
    act=(H0+2.5*14.4/60*15.041)*Z/360
    rows.append(["太初（三统日躔）", n, "", f"{D:.2f}", f"{act:.2f}", f"{D-act:+.2f}"])
out = Path(__file__).resolve().parents[3] / "data/phenomena/checks/sifen_hunzhong.csv"
with open(out, "w", encoding="utf-8", newline="") as f:
    f.write("# 昏中星去日（古度）：表值与实际几何（日入时角 + 2.5 刻，洛阳）比较；差 = 表 − 实际（scripts/calendar_data/qinhan_eval/sifen_hunzhong_check.py）\n")
    w = csv.writer(f)
    w.writerow(["表", "气", "昏中星", "表去日", "实际去日", "差"])
    w.writerows(rows)
for r in rows:
    print(*r)
