/// 按 key 取说明
pub fn rule_info(key: &str) -> Option<&'static RuleInfo> {
    RULE_CATALOG.iter().find(|r| r.key == key)
}

/// 协纪婚事诸神（[`super::yiji_derive::HUN_SHEN`]）之说明：(key `xj:名`, 名, 宜忌, 各书之说)。
/// 协纪一行取 [`super::yiji_derive::HUN_SHEN_INFO`]；同名之神在类编凶神中者，并列其说
pub fn hun_shen_catalog() -> Vec<(String, &'static str, &'static str, Vec<View>)> {
    use super::yiji_derive::{hun_shen_info, HUN_SHEN};
    HUN_SHEN
        .iter()
        .map(|(n, yi)| {
            let (cite, rule, effect) = hun_shen_info(n);
            let mut vs = vec![View { book: "协纪", cite, stance: "立", rule, effect, quote: "" }];
            if let Some(r) = rule_info(&format!("lb:{n}")) {
                vs.extend(r.views.iter().filter(|x| x.book != "协纪").copied());
            }
            (format!("xj:{n}"), *n, if *yi { "宜" } else { "忌" }, vs)
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 目录覆盖诸可取舍之项：类编凶神、诸神、铺注、选项；key 不重
    #[test]
    fn catalog_covers_all() {
        use super::super::jiaqu::LEIBIAN_SHEN;
        use super::super::jiaqu_tongshu::TONGSHU_SHEN;
        use super::super::puzhu::PUZHU_HUN;
        let mut keys: Vec<String> = LEIBIAN_SHEN.iter().map(|n| format!("lb:{n}")).collect();
        keys.extend(TONGSHU_SHEN.iter().map(|(n, _, _)| format!("ts:{n}")));
        keys.extend(PUZHU_HUN.iter().map(|n| format!("pz:{n}")));
        for k in ["xieji", "zt", "useYue", "yangGong", "hongSha", "tianGou", "zhangGuang", "chiKou", "zhiHua", "aoTou", "hengTian", "aotouJiri", "dongGong"] {
            keys.push(k.into());
        }
        let miss: Vec<&String> = keys.iter().filter(|k| rule_info(k).is_none()).collect();
        assert!(miss.is_empty(), "{miss:?}");
        let mut all: Vec<&str> = RULE_CATALOG.iter().map(|r| r.key).collect();
        all.sort();
        let n = all.len();
        all.dedup();
        assert_eq!(n, all.len());
        assert!(RULE_CATALOG.iter().all(|r| !r.views.is_empty()));
        let groups = ["协纪铺注", "协纪改删旧说", "协纪辨讹俗说", "类编", "鳌头", "董公"];
        assert!(RULE_CATALOG.iter().all(|r| groups.contains(&r.group)), "组名");
        assert!(hun_shen_catalog().iter().all(|(_, _, _, v)| !v[0].cite.is_empty()));
    }
}
