/// 一书之说
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct View {
    /// 书：协纪、类编、鳌头、董公、宗镜、轉神厯……
    pub book: &'static str,
    /// 卷篇（页，版本）
    pub cite: &'static str,
    /// 立、不载、斥、删、改、异说
    pub stance: &'static str,
    /// 此书之起例（无则空）
    pub rule: &'static str,
    /// 此书所言所主所忌
    pub effect: &'static str,
    /// 原文摘录
    pub quote: &'static str,
}

/// 一可取舍之项
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RuleInfo {
    pub key: &'static str,
    pub name: &'static str,
    /// 协纪铺注、协纪改删旧说、协纪辨讹俗说、类编、鳌头、董公
    pub group: &'static str,
    pub views: &'static [View],
}

const fn v(book: &'static str, cite: &'static str, stance: &'static str, rule: &'static str, effect: &'static str, quote: &'static str) -> View {
    View { book, cite, stance, rule, effect, quote }
}

