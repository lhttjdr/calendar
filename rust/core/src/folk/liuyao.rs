    /// 一行书中装卦
    struct ShuYao {
        shen: Option<String>,
        qin: String,
        zhi: char,
        wx: char,
        sym: char,
        shi_ying: Option<char>,
        fu: Option<(String, char)>,
        right: Option<(String, char, char, char)>,
    }

    fn parse_line(s: &str) -> ShuYao {
        let mut c: Vec<char> = s.chars().collect();
        let mut shen = None;
        if c.len() > 3 && c[2] == '　' && !LIU_QIN.contains(&c[..2].iter().collect::<String>().as_str()) {
            shen = Some(c[..2].iter().collect());
            c.drain(..3);
        }
        let qin: String = c[..2].iter().collect();
        let (zhi, wx, sym) = (c[2], c[3], c[4]);
        let mut i = 5;
        let mut shi_ying = None;
        if i < c.len() && (c[i] == '世' || c[i] == '應') {
            shi_ying = Some(c[i]);
            i += 1;
        }
        let mut fu = None;
        if i < c.len() && c[i] == '伏' {
            fu = Some((c[i + 1..i + 3].iter().collect(), c[i + 3]));
            i += 5;
        }
        while i < c.len() && c[i] == '　' {
            i += 1;
        }
        let right = (c.len() >= i + 5).then(|| (c[i..i + 2].iter().collect(), c[i + 2], c[i + 3], c[i + 4]));
        ShuYao { shen, qin, zhi, wx, sym, shi_ying, fu, right }
    }

    fn zc(z: char) -> u8 {
        let z = if z == '夘' { '卯' } else { z };
        ZHI.iter().position(|x| x.starts_with(z)).unwrap() as u8
    }

    /// 书称卦名对应之卦（通行名后缀；八纯卦可作「乾」「乾爲天」）；异体字归一
    fn name_to_gua(tok: &str) -> Option<u8> {
        let mut t = tok.to_string();
        for (a, b) in [("恆", "恒"), ("旣", "既"), ("無妄", "无妄"), ("遁", "遯"), ("覆", "履"), ("騫", "蹇"), ("兑", "兌"), ("暌", "睽"), ("卽濟", "既濟"), ("晋", "晉"), ("剥", "剝"), ("観", "觀")] {
            t = t.replace(a, b);
        }
        let mut best: Option<(usize, u8)> = None;
        for g in 0..64u8 {
            let n = gua_name(g);
            let pure = g & 7 == g >> 3;
            let hit = t.ends_with(n) || (pure && (t == n || t.starts_with(&format!("{n}爲")) || t.starts_with(&format!("{n}為"))));
            if hit && best.map_or(true, |(l, _)| n.len() > l) {
                best = Some((n.len(), g));
            }
        }
        best.map(|b| b.1)
    }

    /// 一例逐项比对，返回异处
    fn zsby_diff(e: &(&str, &str, Option<u8>, Option<u8>, &str, &str, [&str; 6])) -> Vec<String> {
        let ls: Vec<ShuYao> = e.6.iter().rev().map(|s| parse_line(s)).collect(); // 初至上
        let values: [u8; 6] = core::array::from_fn(|k| match ls[k].sym {
            '⚊' => 7,
            '⚋' => 8,
            '○' => 9,
            _ => 6,
        });
        let p = pai_gua(values, e.2, e.3, LiuyaoOptions::default());
        let zg = pai_gua(core::array::from_fn(|k| if p.zhi >> k & 1 == 1 { 7 } else { 8 }), None, None, LiuyaoOptions::default());
        let mut d = Vec::new();
        let pos = ["初", "二", "三", "四", "五", "上"];
        if !e.4.is_empty() && name_to_gua(e.4) != Some(p.ben) {
            d.push(format!("卦名：书称「{}」，爻画为{}", e.4, p.ben_name));
        }
        if !e.5.is_empty() && name_to_gua(e.5) != Some(p.zhi) {
            d.push(format!("之卦名：书称「{}」，爻画为{}", e.5, p.zhi_name));
        }
        for k in 0..6 {
            let (l, y) = (&ls[k], &p.yao[k]);
            let wz = WU_XING[zhi_wx(zc(l.zhi)) as usize];
            if zc(l.zhi) != y.zhi {
                d.push(format!("{}爻纳支：书{}，算{}", pos[k], l.zhi, ZHI[y.zhi as usize]));
            } else if !wz.starts_with(l.wx) {
                d.push(format!("{}爻五行：书{}{}", pos[k], l.zhi, l.wx));
            }
            if l.qin != LIU_QIN[y.qin as usize] {
                d.push(format!("{}爻六亲：书{}，算{}", pos[k], l.qin, LIU_QIN[y.qin as usize]));
            }
            let sy = if k + 1 == p.wei.shi as usize { Some('世') } else if k + 1 == p.wei.ying as usize { Some('應') } else { None };
            if l.shi_ying != sy {
                d.push(format!("{}爻世应：书{:?}，算{:?}", pos[k], l.shi_ying, sy));
            }
            if let Some(s) = &l.shen {
                let s = s.replace('靑', "青").replace("元武", "玄武").replace('滕', "螣").replace('媵', "螣");
                match y.shen {
                    Some(m) if LIU_SHEN[m as usize] == s => {}
                    Some(m) => d.push(format!("{}爻六神：书{}，算{}", pos[k], s, LIU_SHEN[m as usize])),
                    None => d.push(format!("{}爻六神：书{}，无日辰", pos[k], s)),
                }
            }
            if let Some((fq, fz)) = &l.fu {
                match y.fu {
                    Some((q, _, z)) if LIU_QIN[q as usize] == fq && z == zc(*fz) => {}
                    other => d.push(format!("{}爻伏神：书{}{}，算{:?}", pos[k], fq, fz, other.map(|f| (LIU_QIN[f.0 as usize], ZHI[f.2 as usize])))),
                }
            }
            if let Some((rq, rz, _rw, rs)) = &l.right {
                let (bz, bq) = match y.bian {
                    Some(b) => (b.1, b.3),
                    None => (zg.yao[k].zhi, ((zg.yao[k].wx + 5 - p.gong_wx) % 5) as u8),
                };
                let want = if p.zhi >> k & 1 == 1 { '⚊' } else { '⚋' };
                if *rs != want {
                    d.push(format!("{}爻之卦爻象：书{}，应{}", pos[k], rs, want));
                }
                if zc(*rz) != bz {
                    d.push(format!("{}爻之卦纳支：书{}，算{}", pos[k], rz, ZHI[bz as usize]));
                }
                if rq != LIU_QIN[bq as usize] {
                    d.push(format!("{}爻之卦六亲：书{}，算{}", pos[k], rq, LIU_QIN[bq as usize]));
                }
            }
        }
        if !ls.iter().any(|l| l.shi_ying == Some('世')) {
            d.push("书未标世".into());
        }
        d
    }

    /// 《增刪卜易》卦例逐例比对（只排卦）。`ZSBY_YI` 为有异处之例（序号，见 doc/folk/liuyao.md「逐例检验」逐条分析）；
    /// `cargo test ... zeng_shan_bu_yi -- --nocapture` 打印逐例表。
    #[test]
    fn zeng_shan_bu_yi() {
        let mut yi = Vec::new();
        for (i, e) in ZSBY.iter().enumerate() {
            let d = zsby_diff(e);
            let ls: Vec<ShuYao> = e.6.iter().rev().map(|s| parse_line(s)).collect();
            let values: [u8; 6] = core::array::from_fn(|k| match ls[k].sym {
                '⚊' => 7,
                '⚋' => 8,
                '○' => 9,
                _ => 6,
            });
            let p = pai_gua(values, e.2, e.3, LiuyaoOptions::default());
            let gua = if p.ben == p.zhi { p.ben_name.to_string() } else { format!("{}之{}", p.ben_name, p.zhi_name) };
            let date = format!(
                "{}{}",
                e.2.map(|m| format!("{}月", ZHI[m as usize])).unwrap_or_default(),
                e.3.map(|r| format!("{}{}日", GAN[(r % 10) as usize], ZHI[(r % 12) as usize])).unwrap_or_default()
            );
            println!("| {} | {} | {} | {} | {} |", i + 1, e.0, date, gua, if d.is_empty() { "合".to_string() } else { d.join("；") });
            if !d.is_empty() {
                yi.push(i + 1);
            }
        }
        println!("相合 {}/{}", ZSBY.len() - yi.len(), ZSBY.len());
        // 比对覆盖：爻数、列之卦之爻、书标六神、书标伏神、书称卦名
        let ls: Vec<ShuYao> = ZSBY.iter().flat_map(|e| e.6.iter().map(|s| parse_line(s))).collect();
        let n_right = ls.iter().filter(|l| l.right.is_some()).count();
        let n_shen = ls.iter().filter(|l| l.shen.is_some()).count();
        let n_fu = ls.iter().filter(|l| l.fu.is_some()).count();
        let n_name = ZSBY.iter().filter(|e| !e.4.is_empty()).count();
        println!("爻 {}，之卦爻 {n_right}，六神 {n_shen}，伏神 {n_fu}，书称卦名 {n_name} 例", ls.len());
        assert_eq!((ls.len(), n_right, n_shen, n_fu), (1788, 1374, 12, 1));
        assert_eq!(yi, ZSBY_YI);
    }
